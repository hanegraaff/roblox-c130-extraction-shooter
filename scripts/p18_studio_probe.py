"""Generate a read-only Studio Edit parity probe from the current test build.

Run after ``verify.py`` (or a fresh Rojo test build), then execute the emitted
Luau through Studio MCP in the confirmed local test document before Play. This
checks loaded script byte lengths/djb2 fingerprints and launcher/platform poses;
it neither synchronizes source nor establishes gameplay/replication acceptance.
The receipt separately binds the full artifact with SHA-256.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build/tests.rbxlx"
OUTPUT = ROOT / "build/p18-studio-probe.luau"


def fingerprint(source: str) -> tuple[int, int]:
    """Return UTF-8 byte length and a portable bounded-integer djb2 checksum."""
    data = source.encode("utf-8")
    value = 5381
    for byte in data:
        value = (value * 33 + byte) % (2 ** 32)
    return len(data), value


def collect(root: ET.Element) -> tuple[list[dict], list[dict]]:
    """Extract actual built Sources and the four pickup/support transforms."""
    scripts: list[dict] = []
    geometry: list[dict] = []
    names = {"LauncherRadar", "LauncherHangar", "LauncherDepot", "LauncherSeedship",
             "SeedshipLauncherPlatform"}

    def visit(item: ET.Element, parent: list[str]) -> None:
        name = item.findtext("Properties/string[@name='Name']")
        if name is None:
            raise ValueError("built Instance has no Name")
        path = parent + [name]
        source = item.find("Properties/ProtectedString[@name='Source']")
        if source is None and item.attrib["class"] in {"Script", "LocalScript", "ModuleScript"}:
            source = item.find("Properties/string[@name='Source']")
        if source is not None:
            length, checksum = fingerprint(source.text or "")
            scripts.append({"path": path, "className": item.attrib["class"],
                            "bytes": length, "djb2": checksum})
        if name in names and path[:3] == ["Workspace", "World", "Battlefield"]:
            pose = item.find("Properties/CoordinateFrame[@name='CFrame']")
            size = item.find("Properties/Vector3[@name='size']")
            if size is None:
                size = item.find("Properties/Vector3[@name='Size']")
            if pose is None or size is None:
                raise ValueError("missing pickup/platform geometry: " + name)
            geometry.append({"path": path, "className": item.attrib["class"],
                             "pose": [float(pose.findtext(axis, "nan")) for axis in
                                      ("X", "Y", "Z", "R00", "R01", "R02", "R10", "R11", "R12", "R20", "R21", "R22")],
                             "size": [float(size.findtext(axis, "nan")) for axis in ("X", "Y", "Z")]})
        for child in item.findall("Item"):
            visit(child, path)

    for item in root.findall("Item"):
        visit(item, [])
    if not scripts or not any(row["path"][:2] == ["ServerScriptService", "ServerTests"] for row in scripts):
        raise ValueError("requires a nonempty test-mapped build")
    if {row["path"][-1] for row in geometry} != names:
        raise ValueError("test build lacks the four P18 pickups and their support platform")
    return scripts, geometry


def main() -> None:
    """Emit a bounded-yielding, read-only parity check and artifact receipt."""
    scripts, geometry = collect(ET.parse(BUILD).getroot())
    receipt = {
        "sourceCommit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "buildSha256": hashlib.sha256(BUILD.read_bytes()).hexdigest(),
        "scriptCount": len(scripts), "geometryCount": len(geometry),
        "sourceComparison": "UTF-8 byte lengths and djb2 checksums; not cryptographic loaded-source proof",
    }
    expected = json.dumps({"scripts": scripts, "geometry": geometry, "receipt": receipt}, separators=(",", ":"))
    probe = '''-- Generated by scripts/p18_studio_probe.py; read-only local Edit check.
assert(game.PlaceId == 0 and game.GameId == 0, "requires the separate local test place")
assert(not game:GetService("RunService"):IsRunning(), "stop Play before source comparison")
local expected = game:GetService("HttpService"):JSONDecode([==[EXPECTED]==])
local mismatches = {}
local expectedScripts = {}
local function resolve(path)
    local owner = game
    for _, name in path do
        owner = owner:FindFirstChild(name)
        if not owner then return nil end
    end
    return owner
end
for index, row in expected.scripts do
    local instance = resolve(row.path)
    local label = table.concat(row.path, "/")
    expectedScripts[label] = true
    if not instance or instance.ClassName ~= row.className then
        table.insert(mismatches, {path = label, reason = "missing/wrong script class"})
    else
        local source, hash = instance.Source, 5381
        for offset = 1, #source do
            hash = (hash * 33 + string.byte(source, offset)) % 4294967296
            if offset % 65536 == 0 then task.wait() end
        end
        if #source ~= row.bytes or hash ~= row.djb2 then
            table.insert(mismatches, {path = label, reason = "source differs", bytes = #source, djb2 = hash})
        end
    end
    if index % 16 == 0 then task.wait() end
end
local managedRoots = {"ReplicatedStorage", "ServerScriptService", "ServerStorage", "StarterPlayer", "Workspace"}
for _, name in managedRoots do
    for _, instance in game:GetService(name):GetDescendants() do
        if instance:IsA("Script") or instance:IsA("LocalScript") or instance:IsA("ModuleScript") then
            local path, ancestor = {}, instance
            while ancestor ~= game do
                table.insert(path, 1, ancestor.Name)
                ancestor = ancestor.Parent
            end
            local label = table.concat(path, "/")
            if not expectedScripts[label] then
                table.insert(mismatches, {path = label, reason = "unexpected source in managed root"})
            end
        end
    end
    task.wait()
end
for _, row in expected.geometry do
    local instance = resolve(row.path)
    local label = table.concat(row.path, "/")
    if not instance or not instance:IsA("BasePart") or instance.ClassName ~= row.className then
        table.insert(mismatches, {path = label, reason = "missing/wrong geometry"})
    else
        local pose = CFrame.new(table.unpack(row.pose))
        local size = Vector3.new(table.unpack(row.size))
        if (instance.Position - pose.Position).Magnitude > 0.001
            or (instance.CFrame.RightVector - pose.RightVector).Magnitude > 0.001
            or (instance.CFrame.UpVector - pose.UpVector).Magnitude > 0.001
            or (instance.Size - size).Magnitude > 0.001
            or not instance.Anchored then
            table.insert(mismatches, {path = label, reason = "pose/size/anchor differs"})
        end
    end
end
return {receipt = expected.receipt, passed = #mismatches == 0,
    comparedScripts = #expected.scripts, comparedGeometry = #expected.geometry,
    mismatches = mismatches}
'''.replace("EXPECTED", expected)
    OUTPUT.write_text(probe)
    receipt["probeSha256"] = hashlib.sha256(probe.encode()).hexdigest()
    (ROOT / "build/p18-studio-probe.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"probe": str(OUTPUT.relative_to(ROOT)), **receipt}, indent=2))


if __name__ == "__main__":
    main()

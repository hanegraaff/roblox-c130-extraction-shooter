"""Build a local release candidate from a clean checkout using the full host gate.

Writes build/release-receipt.json only after verification. The receipt binds the
release and Studio test builds to this commit and inventories their release cloud
asset references. It performs no asset permission checks or Roblox publication.
"""

import hashlib
import json
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

from inspect_build import instance_nodes
from verify import ENVIRONMENT, ROOT, tool_pins


RELEASE = "build/game.rbxlx"
STUDIO_TEST = "build/tests.rbxlx"
RECEIPT = "build/release-receipt.json"
RELEASE_PROJECT = "default.project.json"
STUDIO_TEST_PROJECT = "test.project.json"
MANIFEST = "assets/manifest.json"
IMPORTS = "assets/imports/military-outpost"
MESHES = f"{IMPORTS}/native-mesh-profiles-v1.json"
TEXTURES = f"{IMPORTS}/material-textures-v2.json"
VESPER_RECEIPT = "assets/imports/radar-outpost/native-receipt.json"
VESPER_BANKS = ("assets/models/VesperArray.rbxm", "assets/models/VesperPanelVariants.rbxm")
SALT_FLATS_RECEIPT = "assets/imports/salt-flats/native-receipt.json"
SALT_FLATS_BANKS = ("assets/models/SaltFlatsHangar.rbxm", "assets/models/SaltFlatsPanelVariants.rbxm")
SANDBREAK_RECEIPT = "assets/imports/sandbreak/native-receipt.json"
SANDBREAK_BANKS = ("assets/models/SandbreakBunker.rbxm", "assets/models/SandbreakPanelVariants.rbxm")
SCRIPT_CLASSES = {"Script", "LocalScript", "ModuleScript"}
CLOUD_REFERENCE = re.compile(r"\brbxassetid://([1-9][0-9]*)\b")


def git(root: Path, *arguments: str) -> str:
    return subprocess.check_output(["git", *arguments], cwd=root, text=True).strip()


def mapped_inputs(node: dict) -> set[str]:
    """Collect authored Rojo paths, excluding the Wally install generated by setup."""
    path = node.get("$path")
    paths = {path} if path and path != "Packages" else set()
    for name, child in node.items():
        if not name.startswith("$") and isinstance(child, dict):
            paths.update(mapped_inputs(child))
    return paths


def clean_revision(root: Path) -> dict[str, str]:
    """Reject changes and ignored authored files that could enter either Rojo build."""
    if git(root, "status", "--porcelain=v1", "--untracked-files=all"):
        raise RuntimeError("Release preparation requires a clean Git checkout")
    inputs = mapped_inputs(read_json(root, RELEASE_PROJECT)["tree"]) | mapped_inputs(read_json(root, STUDIO_TEST_PROJECT)["tree"])
    ignored = git(root, "ls-files", "--others", "--ignored", "--exclude-standard", "--", *sorted(inputs))
    if ignored:
        raise RuntimeError(f"Ignored files in authored Rojo inputs:\n{ignored}")
    return {"commit": git(root, "rev-parse", "--verify", "HEAD"),
            "tree": git(root, "rev-parse", "--verify", "HEAD^{tree}")}


def fingerprint(root: Path, relative_path: str) -> dict[str, str | int]:
    """Identify an artifact or input by a portable relative path and exact bytes."""
    content = (root / relative_path).read_bytes()
    return {"path": relative_path, "bytes": len(content), "sha256": hashlib.sha256(content).hexdigest()}


def read_json(root: Path, name: str) -> dict:
    return json.loads((root / name).read_text(encoding="utf-8"))


def source_paths(node: dict, parent: str = "") -> dict[str, str]:
    """Index Rojo runtime scripts from the test sourcemap already built by verify."""
    result = {}
    for child in node.get("children", []):
        instance_path = f"{parent}/{child['name']}" if parent else child["name"]
        files = [file for file in child.get("filePaths", []) if file.startswith("src/")
                 and Path(file).suffix in {".lua", ".luau"}]
        if child["className"] in SCRIPT_CLASSES and files:
            if len(files) != 1:
                raise RuntimeError(f"Ambiguous runtime script source: {instance_path}")
            result[instance_path] = files[0]
        result.update(source_paths(child, instance_path))
    return result


def audit_runtime_sources(root: Path, release: dict[str, ET.Element], studio_test: dict[str, ET.Element],
                          mapping: dict[str, str]) -> int:
    """Require 1:1 runtime source and class equivalence in both inspected builds."""
    scripts = {name for name, node in release.items() if node.attrib["class"] in SCRIPT_CLASSES}
    if not scripts or scripts != mapping.keys():
        raise RuntimeError(f"Runtime script sourcemap/build mismatch: {sorted(scripts ^ mapping.keys())}")
    for name, source in sorted(mapping.items()):
        expected = (root / source).read_text(encoding="utf-8")
        for artifact, nodes in ((RELEASE, release), (STUDIO_TEST, studio_test)):
            node = nodes.get(name)
            if (node is None or node.attrib["class"] != release[name].attrib["class"]
                    or node.findtext("Properties/*[@name='Source']") != expected):
                raise RuntimeError(f"{artifact} script differs from {source}: {name}")
    return len(scripts)


def vesper_assets(root: Path, receipt: dict) -> tuple[set[str], set[str]]:
    """Read native IDs from separately built, receipt-bound import sources."""
    fingerprints = receipt["nativeModelsByPathAndSha256"]
    if set(fingerprints) != set(VESPER_BANKS) or any(
        fingerprint(root, bank)["sha256"] != fingerprints[bank] for bank in VESPER_BANKS
    ):
        raise RuntimeError("Vesper native banks differ from the import receipt")
    # Build the bank inputs independently so a reference added to the full
    # release artifact cannot silently become part of its expected inventory.
    with tempfile.TemporaryDirectory(prefix="vesper-release-inputs-", dir=root / "build") as directory:
        temporary = Path(directory)
        project = temporary / "native.project.json"
        banks = {Path(bank).stem: {"$path": str(root / bank)} for bank in VESPER_BANKS}
        project.write_text(json.dumps({"name": "VesperReleaseInputs", "tree": {
            "$className": "DataModel", "ServerStorage": banks,
        }}), encoding="utf-8")
        artifact = temporary / "native.rbxlx"
        subprocess.run(["rojo", "build", str(project), "--output", str(artifact)],
                       cwd=root, env=ENVIRONMENT, check=True)
        native = instance_nodes(artifact)
    native_mesh_refs = [mesh.findtext("Properties/Content[@name='MeshContent']/uri", "")
                        for mesh in native.values() if mesh.attrib["class"] == "MeshPart"]
    texture_refs = list(receipt["textureIdsByMaterial"].values())
    if not native_mesh_refs or not texture_refs or any(
        not CLOUD_REFERENCE.fullmatch(reference) for reference in native_mesh_refs + texture_refs
    ):
        raise RuntimeError("Vesper native source contains missing or invalid cloud asset IDs")
    return ({ref.removeprefix("rbxassetid://") for ref in native_mesh_refs},
            {ref.removeprefix("rbxassetid://") for ref in texture_refs})



def native_bank_assets(root: Path, label: str, paths: tuple[str, ...], hashes: dict[str, str],
                       mesh_count: int) -> tuple[set[str], set[str]]:
    """Read mesh and texture IDs from independently rebuilt, receipt-bound banks."""
    if set(hashes) != set(paths) or any(
        fingerprint(root, bank)["sha256"] != hashes[bank] for bank in paths
    ):
        raise RuntimeError(f"{label} native banks differ from the import receipt")
    with tempfile.TemporaryDirectory(prefix="native-release-inputs-", dir=root / "build") as directory:
        temporary = Path(directory)
        project = temporary / "native.project.json"
        project.write_text(json.dumps({"name": "NativeReleaseInputs", "tree": {
            "$className": "DataModel", "ServerStorage": {
                Path(bank).stem: {"$path": str(root / bank)} for bank in paths
            },
        }}), encoding="utf-8")
        artifact = temporary / "native.rbxlx"
        subprocess.run(["rojo", "build", str(project), "--output", str(artifact)],
                       cwd=root, env=ENVIRONMENT, check=True)
        nodes = instance_nodes(artifact)
    meshes, textures = set(), set()
    parts = 0
    for item in nodes.values():
        if item.attrib["class"] == "MeshPart":
            parts += 1
        for node in item.findall("Properties/Content"):
            reference = node.findtext("uri")
            if reference:
                match = CLOUD_REFERENCE.fullmatch(reference)
                if not match:
                    raise RuntimeError(f"Invalid {label} cloud reference: {reference}")
                (meshes if node.get("name") == "MeshContent" else textures).add(match[1])
    if parts != mesh_count or not meshes or not textures:
        raise RuntimeError(f"{label} native source cloud inventory is incomplete")
    return meshes, textures


def asset_inventory(root: Path, release: dict[str, ET.Element]) -> dict:
    """Match cloud IDs in the release XML and embedded scripts to checked-in provenance."""
    manifest = read_json(root, MANIFEST)
    mesh_receipt = read_json(root, MESHES)
    mesh_ids = {profile["mesh_id"].removeprefix("rbxassetid://") for profile in mesh_receipt["profiles"]}
    texture_receipt = read_json(root, TEXTURES)
    texture_ids = {material["asset_id"] for material in texture_receipt["materials"].values()}
    audio_ids = {audio["id"] for recipe in manifest["runtime_recipes"]
                 for audio in recipe.get("creator_store_audio", [])}
    vesper_receipt = None
    if (root / VESPER_RECEIPT).exists():
        meshes, textures = vesper_assets(root, read_json(root, VESPER_RECEIPT))
        mesh_ids.update(meshes)
        texture_ids.update(textures)
        vesper_receipt = fingerprint(root, VESPER_RECEIPT)
    native_receipts = {}
    for key, label, receipt_path, paths, count_key in (
        ("salt_flats_native_receipt", "Salt Flats", SALT_FLATS_RECEIPT, SALT_FLATS_BANKS, "meshes"),
        ("sandbreak_native_receipt", "Sandbreak", SANDBREAK_RECEIPT, SANDBREAK_BANKS, "managedMeshCount"),
    ):
        if not (root / receipt_path).exists():
            continue
        receipt = read_json(root, receipt_path)
        meshes, textures = native_bank_assets(root, label, paths, receipt["nativeModels"], receipt[count_key])
        mesh_ids.update(meshes)
        texture_ids.update(textures)
        native_receipts[key] = fingerprint(root, receipt_path)
    expected = mesh_ids | texture_ids | audio_ids
    actual = set()
    for instance in release.values():
        for prop in instance.findall("Properties/*"):
            for value in prop.itertext():
                actual.update(CLOUD_REFERENCE.findall(value))
    if actual != expected:
        raise RuntimeError(f"Release cloud IDs differ from provenance: unexpected {sorted(actual - expected)}, "
                           f"unused {sorted(expected - actual)}")
    return {
        "manifest": {**fingerprint(root, MANIFEST), "schema_version": manifest["schema_version"]},
        "mesh_receipt": fingerprint(root, MESHES),
        "texture_receipt": fingerprint(root, TEXTURES),
        **({"vesper_native_receipt": vesper_receipt} if vesper_receipt else {}),
        **native_receipts,
        "mesh_ids": sorted(mesh_ids, key=int),
        "texture_ids": sorted(texture_ids, key=int),
        "creator_store_audio_ids": sorted(audio_ids, key=int),
        "destination_permissions_verified": False,
    }


def prepare(root: Path) -> None:
    """Run and inspect fresh builds, then atomically record local candidate facts."""
    initial_revision = clean_revision(root)
    receipt = root / RECEIPT
    receipt.unlink(missing_ok=True)
    subprocess.run([sys.executable, "scripts/verify.py"], cwd=root, check=True)
    release = instance_nodes(root / RELEASE)
    studio_test = instance_nodes(root / STUDIO_TEST)
    scripts = audit_runtime_sources(root, release, studio_test, source_paths(read_json(root, "build/sourcemap.json")))
    facts = {
        "schema_version": 1,
        "source": initial_revision,
        "environment": {"system": platform.system(), "machine": platform.machine(), "python": platform.python_version()},
        "host_gate": {"command": "python3 scripts/verify.py", "result": "passed", "runtime_scripts_matched": scripts},
        "toolchain": {"versions": tool_pins(root), "rokit_pins": fingerprint(root, "rokit.toml"),
                      "wally_lock": fingerprint(root, "wally.lock"),
                      "engine_definitions": fingerprint(root, ".tools/globalTypes.d.luau")},
        "release": {**fingerprint(root, RELEASE), "mapping": fingerprint(root, RELEASE_PROJECT),
                    "instances": len(release)},
        "studio_test": {**fingerprint(root, STUDIO_TEST), "mapping": fingerprint(root, STUDIO_TEST_PROJECT),
                        "instances": len(studio_test)},
        "assets": asset_inventory(root, release),
    }
    if clean_revision(root) != initial_revision:
        raise RuntimeError("Git revision changed during release preparation")
    pending = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=receipt.parent, delete=False) as output:
            pending = Path(output.name)
            output.write(json.dumps(facts, indent=2, sort_keys=True) + "\n")
        pending.replace(receipt)
    finally:
        if pending is not None:
            pending.unlink(missing_ok=True)
    print(f"Prepared {RELEASE} with local verification receipt {RECEIPT}.")


if __name__ == "__main__":
    try:
        prepare(ROOT)
    except (OSError, RuntimeError, ValueError, subprocess.CalledProcessError) as error:
        sys.exit(f"Release preparation failed: {error}")
